"""Create a room on first entry when an external platform reserved its slug.

Used by multi-organization deployments: a platform plans meetings and reserves a
room identifier (slug) for each of them, but Meet does not know the slug yet. On
the first entry on an unknown slug, Meet asks the platform whether a planned
meeting reserved it. If so, and if the meeting is planned, not canceled, inside
its time window and the user may open it, the room is created for the
organization of the meeting. Disabled when SCHEDULED_ROOMS_URL is empty (default);
a slug unknown to the platform keeps the upstream behavior (room not found).

The creation fails closed: an unavailable platform, an unreadable answer or a
refused creation check never creates a room. Once the room exists, the entry is
the usual one (and as lenient as the room limits: fail open).
"""

import logging
import re
import uuid
from datetime import datetime, timedelta
from datetime import timezone as dt_timezone
from typing import Optional

from django.conf import settings
from django.core.exceptions import ValidationError
from django.db import IntegrityError, transaction
from django.utils import timezone

import requests

from core import analytics, models
from core.services.room_creation_check import (
    REASON_PATTERN,
    RoomCreationRefused,
    ensure_room_creation_allowed,
)

logger = logging.getLogger(__name__)

# Format of the identifiers generated by Meet (and by the platform): abc-defg-hij.
SLUG_PATTERN = re.compile(r"^[a-z]{3}-[a-z]{4}-[a-z]{3}$")

REFUSAL_MESSAGES = {
    "scheduled_meeting_not_started": "This meeting has not started yet.",
    "scheduled_meeting_not_opened": "The organizer has not opened this meeting yet.",
    "scheduled_meeting_canceled": "This meeting has been canceled.",
    "scheduled_meeting_ended": "This meeting is over.",
    "check_unavailable": (
        "Room creation is temporarily unavailable, please try again later."
    ),
}
DEFAULT_REFUSAL_MESSAGE = "You are not allowed to open this meeting."


def _refuse(code):
    return RoomCreationRefused(
        REFUSAL_MESSAGES.get(code, DEFAULT_REFUSAL_MESSAGE), code=code
    )


def _parse_datetime(value) -> datetime:
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=dt_timezone.utc)
    return parsed


def _token():
    return settings.ROOM_CREATION_CHECK_TOKEN


def _lookup(slug, user) -> Optional[dict]:
    """Ask the platform about a slug.

    Returns None when the platform does not know it, the validated description of
    the meeting otherwise. Raises ValueError (unusable answer) or
    requests.RequestException (platform unreachable).
    """
    response = requests.post(
        settings.SCHEDULED_ROOMS_URL,
        json={
            "slug": slug,
            "user_sub": user.sub if user.is_authenticated else "",
        },
        headers={"Authorization": f"Bearer {_token()}"},
        timeout=settings.SCHEDULED_ROOMS_TIMEOUT,
    )
    response.raise_for_status()
    result = response.json()
    if not isinstance(result, dict) or not isinstance(result.get("exists"), bool):
        raise ValueError("unexpected body")
    if not result["exists"]:
        return None
    if result.get("status") not in ("scheduled", "canceled"):
        raise ValueError("unknown status")
    meeting = {
        "organization_id": uuid.UUID(str(result["organization_id"])),
        "status": result["status"],
        "starts_at": _parse_datetime(result["starts_at"]),
        "ends_at": _parse_datetime(result["ends_at"]),
        "organizer_sub": result.get("organizer_sub"),
        "user_may_open": result.get("user_may_open") is True,
        "refused_reason": result.get("refused_reason"),
    }
    if not isinstance(meeting["organizer_sub"], str):
        meeting["organizer_sub"] = None
    return meeting


def _check_may_open(meeting, user):
    """Raise the refusal matching the state of the meeting, in a stable order."""
    now = timezone.now()
    if meeting["status"] == "canceled":
        raise _refuse("scheduled_meeting_canceled")
    if now >= meeting["ends_at"]:
        raise _refuse("scheduled_meeting_ended")
    reason = meeting["refused_reason"]
    if reason:
        # Plan without scheduling, inactive organization...: decided by the platform.
        code = (
            reason
            if isinstance(reason, str) and REASON_PATTERN.match(reason)
            else "refused"
        )
        raise _refuse(code)
    early = timedelta(minutes=settings.SCHEDULED_ROOMS_EARLY_ENTRY_MINUTES)
    if now < meeting["starts_at"] - early:
        raise _refuse("scheduled_meeting_not_started")
    if (
        not user.is_authenticated
        or not meeting["user_may_open"]
        or user.organization_id != meeting["organization_id"]
    ):
        # Guests, other members: the room is opened by the organizer (or an
        # administrator); they enter with the link afterwards.
        raise _refuse("scheduled_meeting_not_opened")


def _create_room(slug, user, meeting) -> models.Room:
    save_kwargs = {}
    if user.default_room_access_level not in (None, ""):
        save_kwargs["access_level"] = user.default_room_access_level
    if user.default_room_configuration not in (None, {}):
        save_kwargs["configuration"] = user.default_room_configuration
    with transaction.atomic():
        room = models.Room.objects.create(
            name=slug, organization_id=meeting["organization_id"], **save_kwargs
        )
        models.ResourceAccess.objects.create(
            resource=room, user=user, role=models.RoleChoices.OWNER
        )
        organizer = (
            models.User.objects.filter(sub=meeting["organizer_sub"]).first()
            if meeting["organizer_sub"]
            else None
        )
        if organizer is not None and organizer.pk != user.pk:
            models.ResourceAccess.objects.create(
                resource=room, user=organizer, role=models.RoleChoices.OWNER
            )
    return room


def _announce_room(slug, room) -> None:
    """Tell the platform which room holds the meeting (best effort)."""
    url = settings.SCHEDULED_ROOMS_ROOM_URL
    if not url:
        return
    try:
        response = requests.post(
            url,
            json={"slug": slug, "room_id": str(room.id)},
            headers={"Authorization": f"Bearer {_token()}"},
            timeout=settings.SCHEDULED_ROOMS_TIMEOUT,
        )
        if response.status_code != 200:
            logger.warning(
                "Scheduled room not announced: HTTP %s", response.status_code
            )
    except requests.RequestException as error:
        logger.warning("Scheduled room not announced: %s", type(error).__name__)


def get_or_create_scheduled_room(slug, user) -> Optional[models.Room]:
    """Return the room of a meeting planned for this slug, creating it if needed.

    Returns None when nothing applies (feature disabled, slug that cannot have been
    reserved, slug unknown to the platform, or platform unreachable for an
    anonymous user, who could not create anything): the caller keeps the upstream
    behavior. Raises RoomCreationRefused (HTTP 403, with a ``code``) when the
    meeting exists but the user cannot enter it, and when the platform cannot be
    reached for an authenticated user (fail closed).
    """
    if not settings.SCHEDULED_ROOMS_URL or not SLUG_PATTERN.match(slug):
        return None

    try:
        meeting = _lookup(slug, user)
    except (requests.RequestException, ValueError, KeyError, TypeError) as error:
        logger.warning("Scheduled meeting lookup failed: %s", type(error).__name__)
        if not user.is_authenticated:
            return None
        raise _refuse("check_unavailable") from error
    if meeting is None:
        return None

    _check_may_open(meeting, user)

    # Idempotent: the room may have been created since the first lookup.
    existing = models.Room.objects.filter(slug=slug).first()
    if existing is not None:
        return existing

    ensure_room_creation_allowed(user)
    try:
        room = _create_room(slug, user, meeting)
    except (IntegrityError, ValidationError):
        # Two simultaneous first entries: the loser reads the room of the winner.
        existing = models.Room.objects.filter(slug=slug).first()
        if existing is None:
            raise
        return existing

    _announce_room(slug, room)
    analytics.capture(
        user,
        analytics.AnalyticsEvent.ROOM_CREATED,
        {
            "room_id": str(room.pk),
            "access_level": room.access_level,
            "from_callback": False,
            "scheduled": True,
        },
    )
    return room
